import { defineConfig } from "vite";
import react from "@vitejs/plugin-react-swc";
import path from "path";
import { componentTagger } from "lovable-tagger";

// Keep Rollup's default chunk graph. Manually splitting React, Radix and other
// React-dependent packages into separate vendor chunks caused a production
// initialization cycle where Radix evaluated before React was available.
// Correct runtime ordering takes priority over suppressing chunk-size warnings.

// https://vitejs.dev/config/
export default defineConfig(({ mode }) => ({
  server: {
    host: "::",
    port: 8080,
    hmr: {
      overlay: false,
    },
  },
  plugins: [react(), mode === "development" && componentTagger()].filter(Boolean),
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "./src"),
    },
  },
}));
